/*
Перепишите выражения в тетрадь.
Рядом запишите результат, который ожидаете.
Проверьте каждое через System.out.println.
Для каждого несовпадения объясните причину.
17 / 5
17 % 5
17 / 5.0
-17 / 5
2 + 3 * 4
(2 + 3) * 4
"Итог: " + 2 + 3
2 + 3 + " итог"
'A' + 1
(int) 9.99
 */
public class FromPresentation3_1 {
    public static void main(String[] args) {
        System.out.println("First:\t" + 17 / 5);//Выдает значение целое, из-за того, что оба числа целые, значит тип integer
        System.out.println("Second:\t" + 17 % 5);//Выдает остаток от деления
        System.out.println("Third:\t" + 17 / 5.0);//Выдает результат уже точный, так как второе число представлено как тип double
        System.out.println("Fourth:\t" + -17 / 5);//Выдает значение отрицательное целое, из-за того, что оба числа целые,
                                                  // но одно из них отрицательное, значит тип integer со знаком -
        System.out.println("Fifth:\t" +(2 + 3 * 4));//Так как нет скобок, выполнение идет по правилу математики, если бы не было скобок,
                                                    //результат получится 212
        System.out.println("Sixth:\t" +(2 + 3) * 4);//Вычисление по правилу математики. Сначала скобки.
        System.out.println("Итог: " + 2 + 3);//Неявное преобразование типов. Первое значение строка, а + означает конкатенацию.
        System.out.println(2 + 3 + " итог");//В этом случае, сначала выполняется выражение, затем уже добавляется строка.
        System.out.println('A' + 1);//В одинарных ковычках - это символ, который приобразуется в код и выполняется сложение с 1
        //(int) 9.99 будет 9, так как в int только целое число, все остальное отбрасывается
    }
}
